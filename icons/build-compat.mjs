#!/usr/bin/env node
/**
 * Generates the deprecated `icons/es5/` and `icons/jsx/` folders, which keep old import paths working:
 *
 *   import { Add } from '@openedx/paragon/icons/es5';     // re-exports everything from '@openedx/paragon/icons'
 *   import Add from '@openedx/paragon/icons/es5/Add';     // default export of a single icon
 *   import Add from '@openedx/paragon/icons/jsx/Add';     // same
 *
 * These used to hold one generated component per icon. Now every icon lives in `icons/index.js`, and these
 * files only re-export from it. They are generated at build time (`make build`) and are not committed.
 * New code should use `import { Add } from '@openedx/paragon/icons'`.
 *
 * TypeScript users see these imports as deprecated:
 *   - `es5/index` gets generated types (below), with each icon marked `@deprecated`;
 *   - the single-icon files are covered by one wildcard declaration in `deprecated-paths.d.ts`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS_DIR = path.dirname(fileURLToPath(import.meta.url));
const DEPRECATED = "@deprecated Import icons from '@openedx/paragon/icons' instead.";

// Each line of index.js looks like: export const Pgn5G = /*#__PURE__*/ icon("5G", [...]);
const icons = [...fs.readFileSync(path.join(ICONS_DIR, 'index.js'), 'utf8')
  .matchAll(/^export const (\w+) = \/\*#__PURE__\*\/ icon\("(\w+)"/gm)]
  .map(([, exportName, fileName]) => ({ exportName, fileName }));
if (icons.length === 0) { throw new Error('No icons found in index.js'); }

function writeDir(dir, files) {
  const fullDir = path.join(ICONS_DIR, dir);
  fs.rmSync(fullDir, { recursive: true, force: true });
  fs.mkdirSync(fullDir);
  for (const [file, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(fullDir, file), content);
  }
}

const header = `// ${DEPRECATED}\n// Generated by build-compat.mjs.\n`;
const reexportAll = `${header}export * from '../index.js';\n`;
const singleIconFiles = (ext) => Object.fromEntries(icons.map(({ exportName, fileName }) => [
  `${fileName}.${ext}`,
  `${header}export { ${exportName} as default } from '../index.js';\n`,
]));

writeDir('es5', {
  'index.js': reexportAll,
  'index.d.ts': `${header}import type * as icons from '../index';\n\n${icons.map(({ exportName }) => (
    `/** ${DEPRECATED} */\nexport declare const ${exportName}: typeof icons.${exportName};`
  )).join('\n')}\n`,
  ...singleIconFiles('js'),
});
writeDir('jsx', { 'index.jsx': reexportAll, ...singleIconFiles('jsx') });

console.log(`Generated deprecated es5/ and jsx/ re-exports for ${icons.length} icons`);
